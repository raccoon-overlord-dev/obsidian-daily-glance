const TABLES: Record<string, Strings> = { en, it, fr, de, es };

export const LANGUAGES = {
	auto: "Same as Obsidian",
	en: "English",
	it: "Italiano",
	fr: "Français",
	de: "Deutsch",
	es: "Español",
};
export type Language = keyof typeof LANGUAGES;

let locale = "en";
let strings: Strings = en;

// "auto" reads moment's global locale, which Obsidian sets to its app language.
export function setLanguage(lang: Language): void {
	locale = lang === "auto" ? moment.locale() : lang;
	strings = TABLES[locale.split("-")[0] ?? ""] ?? en;
}

export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
	return strings[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

// moment in the widget's language, without touching Obsidian's global locale.
export const m = (input?: moment.MomentInput, format?: string) => moment(input, format).locale(locale);
export const localeData = () => moment.localeData(locale);
